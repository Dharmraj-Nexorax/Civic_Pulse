CREATE TABLE IF NOT EXISTS issues (
  id VARCHAR(36) PRIMARY KEY,
  organization_id VARCHAR(36) NOT NULL,
  ward_id VARCHAR(36) NOT NULL,
  category_id VARCHAR(36) NOT NULL,
  status ENUM('REPORTED','VERIFICATION','GROUPED','PRIORITIZED','ASSIGNED','IN_PROGRESS','RESOLVED','CITIZEN_VERIFIED','REOPENED') NOT NULL DEFAULT 'REPORTED',
  title VARCHAR(255) NOT NULL,
  summary TEXT NULL,
  summary_source ENUM('ai','fallback') NULL,
  lat DOUBLE NOT NULL,
  lng DOUBLE NOT NULL,
  primary_complaint_id VARCHAR(36) NULL,
  severity ENUM('MINOR','SMALL_LOCAL','SIGNIFICANT','SERIOUS','DANGEROUS') NOT NULL DEFAULT 'SMALL_LOCAL',
  severity_reviewed TINYINT(1) NOT NULL DEFAULT 0,
  context ENUM('NORMAL','SENSITIVE_LOCATION','PUBLIC_FACILITY','EMERGENCY','PUBLIC_SAFETY') NOT NULL DEFAULT 'NORMAL',
  affected_override INT NULL,
  priority_score SMALLINT NOT NULL DEFAULT 0,
  priority_band ENUM('LOW','MEDIUM','HIGH','CRITICAL') NOT NULL DEFAULT 'LOW',
  priority_breakdown JSON NOT NULL,
  priority_override_band ENUM('LOW','MEDIUM','HIGH','CRITICAL') NULL,
  priority_override_reason TEXT NULL,
  verification_flags JSON NOT NULL,
  assigned_team_id VARCHAR(36) NULL,
  assigned_worker_id VARCHAR(36) NULL,
  assigned_at TIMESTAMP NULL,
  started_at TIMESTAMP NULL,
  resolved_at TIMESTAMP NULL,
  verified_at TIMESTAMP NULL,
  reopened_count INT NOT NULL DEFAULT 0,
  approved_external_delay_hours DECIMAL(8,2) NOT NULL DEFAULT 0.00,
  merged_into_issue_id VARCHAR(36) NULL,
  is_demo TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  address TEXT NULL,
  city VARCHAR(100) DEFAULT 'Mandsaur',
  district VARCHAR(100) DEFAULT 'Mandsaur',
  state VARCHAR(100) DEFAULT 'Madhya Pradesh',
  country VARCHAR(100) DEFAULT 'India',
  postal_code VARCHAR(32) NULL,
  CONSTRAINT fk_issues_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_issues_ward FOREIGN KEY (ward_id) REFERENCES wards(id),
  CONSTRAINT fk_issues_category FOREIGN KEY (category_id) REFERENCES categories(id),
  CONSTRAINT fk_issues_team FOREIGN KEY (assigned_team_id) REFERENCES teams(id) ON DELETE SET NULL,
  CONSTRAINT fk_issues_worker FOREIGN KEY (assigned_worker_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_issues_merged FOREIGN KEY (merged_into_issue_id) REFERENCES issues(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS complaints (
  id VARCHAR(36) PRIMARY KEY,
  complaint_no BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
  organization_id VARCHAR(36) NOT NULL,
  issue_id VARCHAR(36) NOT NULL,
  citizen_id VARCHAR(36) NOT NULL,
  ward_id VARCHAR(36) NOT NULL,
  category_id VARCHAR(36) NOT NULL,
  description TEXT NOT NULL,
  lat DOUBLE NOT NULL,
  lng DOUBLE NOT NULL,
  is_primary TINYINT(1) NOT NULL DEFAULT 0,
  joined_existing TINYINT(1) NOT NULL DEFAULT 0,
  is_demo TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  address TEXT NULL,
  city VARCHAR(100) DEFAULT 'Mandsaur',
  district VARCHAR(100) DEFAULT 'Mandsaur',
  state VARCHAR(100) DEFAULT 'Madhya Pradesh',
  country VARCHAR(100) DEFAULT 'India',
  postal_code VARCHAR(32) NULL,
  location_method ENUM('GPS', 'MANUAL') DEFAULT 'MANUAL',
  location_confirmed TINYINT(1) DEFAULT 1,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_complaints_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_complaints_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_complaints_citizen FOREIGN KEY (citizen_id) REFERENCES users(id),
  CONSTRAINT fk_complaints_ward FOREIGN KEY (ward_id) REFERENCES wards(id),
  CONSTRAINT fk_complaints_category FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS assignments (
  id VARCHAR(36) PRIMARY KEY,
  issue_id VARCHAR(36) NOT NULL,
  team_id VARCHAR(36) NOT NULL,
  worker_id VARCHAR(36) NOT NULL,
  assigned_by VARCHAR(36) NOT NULL,
  assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  accepted_at TIMESTAMP NULL,
  band_at_assignment ENUM('LOW','MEDIUM','HIGH','CRITICAL') NOT NULL,
  expected_hours INT NOT NULL,
  start_was_timely TINYINT(1) NULL,
  ended_at TIMESTAMP NULL,
  ended_reason ENUM('RESOLVED','REASSIGNED') NULL,
  reassign_reason TEXT NULL,
  CONSTRAINT fk_assignments_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_assignments_team FOREIGN KEY (team_id) REFERENCES teams(id),
  CONSTRAINT fk_assignments_worker FOREIGN KEY (worker_id) REFERENCES users(id),
  CONSTRAINT fk_assignments_by FOREIGN KEY (assigned_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS resolutions (
  id VARCHAR(36) PRIMARY KEY,
  issue_id VARCHAR(36) NOT NULL,
  assignment_id VARCHAR(36) NULL,
  worker_id VARCHAR(36) NOT NULL,
  resolved_by_role ENUM('WORKER','ADMIN') NOT NULL,
  note TEXT NOT NULL,
  ai_draft_used TINYINT(1) NOT NULL DEFAULT 0,
  proof_count INT NOT NULL DEFAULT 0,
  resolved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  elapsed_hours DECIMAL(10,2) NOT NULL,
  external_delay_hours DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  effective_hours DECIMAL(10,2) NOT NULL,
  expected_hours INT NOT NULL,
  on_time TINYINT(1) NOT NULL,
  citizen_decision ENUM('PENDING','VERIFIED','REJECTED') NOT NULL DEFAULT 'PENDING',
  decided_at TIMESTAMP NULL,
  reject_reason TEXT NULL,
  CONSTRAINT fk_resolutions_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_resolutions_assignment FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE SET NULL,
  CONSTRAINT fk_resolutions_worker FOREIGN KEY (worker_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS media (
  id VARCHAR(36) PRIMARY KEY,
  organization_id VARCHAR(36) NOT NULL,
  uploader_id VARCHAR(36) NOT NULL,
  kind ENUM('COMPLAINT','RESOLUTION_PROOF') NOT NULL,
  complaint_id VARCHAR(36) NULL,
  issue_id VARCHAR(36) NULL,
  resolution_id VARCHAR(36) NULL,
  storage_path VARCHAR(500) NOT NULL,
  mime VARCHAR(100) NOT NULL,
  size_bytes BIGINT NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_media_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_media_uploader FOREIGN KEY (uploader_id) REFERENCES users(id),
  CONSTRAINT fk_media_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
  CONSTRAINT fk_media_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_media_resolution FOREIGN KEY (resolution_id) REFERENCES resolutions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ratings (
  id VARCHAR(36) PRIMARY KEY,
  resolution_id VARCHAR(36) NOT NULL UNIQUE,
  issue_id VARCHAR(36) NOT NULL,
  citizen_id VARCHAR(36) NOT NULL,
  worker_id VARCHAR(36) NOT NULL,
  stars SMALLINT NOT NULL CHECK (stars BETWEEN 1 AND 5),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ratings_resolution FOREIGN KEY (resolution_id) REFERENCES resolutions(id) ON DELETE CASCADE,
  CONSTRAINT fk_ratings_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_ratings_citizen FOREIGN KEY (citizen_id) REFERENCES users(id),
  CONSTRAINT fk_ratings_worker FOREIGN KEY (worker_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS issue_events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  issue_id VARCHAR(36) NOT NULL,
  actor_id VARCHAR(36) NULL,
  actor_role ENUM('SYSTEM','CITIZEN','WORKER','ADMIN') NOT NULL,
  event_type VARCHAR(100) NOT NULL,
  from_status ENUM('REPORTED','VERIFICATION','GROUPED','PRIORITIZED','ASSIGNED','IN_PROGRESS','RESOLVED','CITIZEN_VERIFIED','REOPENED') NULL,
  to_status ENUM('REPORTED','VERIFICATION','GROUPED','PRIORITIZED','ASSIGNED','IN_PROGRESS','RESOLVED','CITIZEN_VERIFIED','REOPENED') NULL,
  note TEXT NULL,
  metadata JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_events_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
  CONSTRAINT fk_events_actor FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notifications (
  id VARCHAR(36) PRIMARY KEY,
  user_id VARCHAR(36) NOT NULL,
  issue_id VARCHAR(36) NULL,
  type VARCHAR(100) NOT NULL,
  message TEXT NOT NULL,
  is_read TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_notifications_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ai_suggestions (
  id VARCHAR(36) PRIMARY KEY,
  organization_id VARCHAR(36) NOT NULL,
  kind ENUM('CATEGORY','SIMILAR_ISSUE','SUMMARY','STATUS_EXPLAIN','COPILOT','RESOLUTION_REPORT','ADMIN_INSIGHT') NOT NULL,
  method VARCHAR(100) NOT NULL,
  complaint_id VARCHAR(36) NULL,
  issue_id VARCHAR(36) NULL,
  payload JSON NOT NULL,
  accepted TINYINT(1) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ai_sug_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_ai_sug_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(id) ON DELETE CASCADE,
  CONSTRAINT fk_ai_sug_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
